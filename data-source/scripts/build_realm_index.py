#!/usr/bin/env python3
"""Build site/data/realm-index.json: which era maps each realm appears on.

The map's "Find in History" search uses it to find realms in any period, not just the
year on screen. In this repository, run it from data-source/scripts/ whenever an era map in
site/eras/ changes:

    python3 build_realm_index.py

(The website repository keeps the same script at scripts/build_realm_index.py.)

Output (compact JSON):
    { "about": ..., "r": [[name, g, kind, peakY, [eraY, ...]], ...] }
One row per name a realm carries on the maps (the same realm may be "Roman Republic" on
one map and "Roman Empire" on the next). g is the realm's index in data/eras.json
"realms" (its colour and identity on the map), kind is 0 for a state and 1 for a people or
culture, peakY is the era year in which it covers the most land under that name (the
search jumps there), and the list holds every era year it appears in under that name.
"""
import json
from pathlib import Path

SITE = Path(__file__).resolve().parents[2] / 'site'
meta = json.loads((SITE / 'data' / 'eras.json').read_text(encoding='utf-8'))
DEEP = SITE / 'data' / 'deep.json'   # the deep-time layer lives in the website repository only
deep_end = json.loads(DEEP.read_text(encoding='utf-8')).get('deepEnd', -10000) if DEEP.exists() else -10000
seen = {}
for e in meta['eras']:
    if e['y'] < deep_end:
        continue   # deep-time maps show human species, not realms
    p = SITE / 'eras' / f"{e['f']}.json"
    if not p.exists():
        continue
    js = json.loads(p.read_text(encoding='utf-8'))
    area, state = {}, {}
    for ent in js['ents']:
        r = ent.get('r', -1)
        if r is None or r < 0 or not ent.get('a'):
            continue
        area[r] = area.get(r, 0) + ent['a']
        if not ent.get('k'):
            state[r] = True
    for i, r in enumerate(js['realms']):
        if not area.get(i):
            continue
        key = (r.get('n') or meta['realms'][r['g']]['n'], r['g'])
        s = seen.setdefault(key, {'ys': [], 'peak': (0, None), 'state': False})
        s['ys'].append(e['y'])
        if area[i] > s['peak'][0]:
            s['peak'] = (area[i], e['y'])
        s['state'] = s['state'] or state.get(i, False)
rows = [[n, g, 0 if s['state'] else 1, s['peak'][1], sorted(set(s['ys']))] for (n, g), s in sorted(seen.items(), key=lambda kv: (kv[0][0].lower(), kv[0][1]))]
out = {
    'about': 'Generated by scripts/build_realm_index.py from site/eras/. Do not edit by hand. Derived from the map border data, which is GPL-3.0 (see /credits). Rows: [name, realm index in eras.json, kind (0 state, 1 people), era year of largest extent, era years it appears in under this name].',
    'r': rows,
}
(SITE / 'data' / 'realm-index.json').write_text(json.dumps(out, ensure_ascii=False, separators=(',', ':')), encoding='utf-8')
print(f'{len(rows)} realm names indexed from {len(meta["eras"])} eras')
