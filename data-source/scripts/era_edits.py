"""Corrections layered on top of the historical-basemaps snapshots, plus derived key years.

Every change is an operation on the era's land-ownership raster, so the source data stays untouched
and each fix can be removed by deleting its line. Province names are Natural Earth admin-1 names;
country codes are Natural Earth ADM0_A3. Operations:

  ren   rename an entity (merges into the target if that name already exists)
  set   change realm / kind of an entity
  asg   give land to an entity (created if new). Where = a0 (countries), a1 (provinces),
        a1x (all provinces of a country except), cont (continent); limited by frm (current owners)
  copy  copy one entity's land from another year's source map
  fill  fill unclaimed land from another (already corrected) year, with a rename map
  realm_reset  make every subject of a realm independent (optionally reassign some)
  realm_a0     give every state mostly inside these countries a new realm
Each op may carry 'n': a short note shown in the atlas' change log for that year.
"""

